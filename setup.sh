#!/usr/bin/env bash

# Bootstraps a machine: installs git and the GitHub CLI, makes sure gh is
# authenticated, and installs the dotfiles commands into ~/.local/bin.
# Works on macOS, Linux (apt/dnf/pacman) and Windows via Git Bash (winget).
# Safe to run multiple times.

set -euo pipefail

ROOT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
# shellcheck source=lib/common.sh
source "$ROOT_DIR/lib/common.sh"

BIN_DIR="$HOME/.local/bin"
DRY_RUN=false

for arg in "$@"; do
  case "$arg" in
    --dry-run) DRY_RUN=true ;;
    -h | --help)
      echo "Usage: ./setup.sh [--dry-run]"
      exit 0
      ;;
    *)
      log_error "Unknown option: $arg"
      exit 1
      ;;
  esac
done

# Runs a command, or only prints it when --dry-run is set.
run() {
  if [ "$DRY_RUN" = true ]; then
    printf '[dry-run] %s\n' "$*"
  else
    "$@"
  fi
}

PKG_MANAGER="$(detect_package_manager)"
OS="$(detect_os)"
log_info "Detected OS: $OS, package manager: $PKG_MANAGER"

if [ "$OS" = "macos" ] && [ "$PKG_MANAGER" = "unknown" ]; then
  log_error "Homebrew is required on macOS. Install it from https://brew.sh and re-run."
  exit 1
fi

# The default Debian/Ubuntu repos ship an outdated gh, so add GitHub's official
# apt repository first (https://github.com/cli/cli/blob/trunk/docs/install_linux.md).
install_gh_apt() {
  run sudo mkdir -p -m 755 /etc/apt/keyrings
  if [ "$DRY_RUN" = true ]; then
    echo "[dry-run] add GitHub CLI apt repository"
  else
    curl -fsSL https://cli.github.com/packages/githubcli-archive-keyring.gpg \
      | sudo tee /etc/apt/keyrings/githubcli-archive-keyring.gpg >/dev/null
    sudo chmod go+r /etc/apt/keyrings/githubcli-archive-keyring.gpg
    echo "deb [arch=$(dpkg --print-architecture) signed-by=/etc/apt/keyrings/githubcli-archive-keyring.gpg] https://cli.github.com/packages stable main" \
      | sudo tee /etc/apt/sources.list.d/github-cli.list >/dev/null
  fi
  run sudo apt-get update
  run sudo apt-get install -y gh
}

# Installs a package only when its command is missing, using whichever package
# manager was detected. Arguments are the per-manager package names:
# install_package <command> <brew> <apt> <dnf> <pacman> <winget-id>
install_package() {
  local cmd="$1" brew_pkg="$2" apt_pkg="$3" dnf_pkg="$4" pacman_pkg="$5" winget_id="$6"

  if has_cmd "$cmd"; then
    log_ok "$cmd already installed"
    return 0
  fi

  log_info "Installing $cmd..."
  case "$PKG_MANAGER" in
    brew) run brew install "$brew_pkg" ;;
    apt)
      if [ "$cmd" = "gh" ]; then
        install_gh_apt
      else
        run sudo apt-get install -y "$apt_pkg"
      fi
      ;;
    dnf) run sudo dnf install -y "$dnf_pkg" ;;
    pacman) run sudo pacman -S --noconfirm "$pacman_pkg" ;;
    winget)
      run winget install --id "$winget_id" -e --accept-source-agreements --accept-package-agreements
      ;;
    *)
      log_error "No supported package manager found. Install $cmd manually."
      return 1
      ;;
  esac
}

install_package git git git git git Git.Git
install_package gh gh gh gh github-cli GitHub.cli

# Authentication is skipped on dry runs because gh auth login is interactive.
if [ "$DRY_RUN" = false ] && has_cmd gh; then
  if gh auth status >/dev/null 2>&1; then
    log_ok "gh is authenticated"
  else
    log_info "gh is not authenticated, starting login..."
    gh auth login
  fi
fi

# Installed without the .sh extension so Git can expose git-* scripts as
# subcommands (for example, `git sync-fork`).
install_command() {
  local source="$1" target="$2" command_name="$3" alias_name="$4" status

  if [ ! -e "$target" ]; then
    status="missing; would install"
  elif cmp -s "$source" "$target"; then
    status="already up to date"
    if [ "$DRY_RUN" = true ]; then
      log_ok "$command_name $status"
      return
    fi
  else
    status="out of date; would update"
  fi

  if [ "$DRY_RUN" = true ]; then
    log_info "$command_name $status"
    printf '[dry-run] cp %s %s\n' "$source" "$target"
    printf '[dry-run] chmod +x %s\n' "$target"
  else
    mkdir -p "$BIN_DIR"
    cp "$source" "$target"
    chmod +x "$target"
    log_ok "Installed $command_name (also available as: git $alias_name)"
  fi
}

# Unlike the git commands, this one is a wrapper that runs the script from this
# checkout, because it needs the tracked vscode/extensions.txt next to it.
install_wrapper() {
  local script="$1" target="$2" command_name="$3" content status

  content="$(printf '#!/usr/bin/env bash\n# Generated by dotfiles setup; runs the script from the dotfiles checkout.\nexec %q "$@"' "$script")"

  if [ ! -e "$target" ]; then
    status="missing; would install"
  elif [ "$(cat "$target")" = "$content" ]; then
    status="already up to date"
    if [ "$DRY_RUN" = true ]; then
      log_ok "$command_name $status"
      return
    fi
  else
    status="out of date; would update"
  fi

  if [ "$DRY_RUN" = true ]; then
    log_info "$command_name $status"
    printf '[dry-run] write wrapper %s -> %s\n' "$target" "$script"
    printf '[dry-run] chmod +x %s\n' "$target"
  else
    mkdir -p "$BIN_DIR"
    printf '%s\n' "$content" >"$target"
    chmod +x "$target"
    log_ok "Installed $command_name (runs $script)"
  fi
}

log_info "Installing commands into $BIN_DIR"
install_command "$ROOT_DIR/git/git-sync-fork.sh" "$BIN_DIR/git-sync-fork" "git-sync-fork" "sync-fork"
install_command "$ROOT_DIR/git/git-prune-branches.sh" "$BIN_DIR/git-prune-branches" "git-prune-branches" "prune-branches"
install_wrapper "$ROOT_DIR/vscode/sync-extensions.sh" "$BIN_DIR/vscode-sync-extensions" "vscode-sync-extensions"
install_wrapper "$ROOT_DIR/vscode/sync-settings.sh" "$BIN_DIR/vscode-sync-settings" "vscode-sync-settings"

# Only warn: editing shell profiles automatically varies too much per shell.
case ":$PATH:" in
  *":$BIN_DIR:"*) ;;
  *) log_warn "$BIN_DIR is not on your PATH. Add: export PATH=\"\$HOME/.local/bin:\$PATH\"" ;;
esac

log_ok "Setup complete"
