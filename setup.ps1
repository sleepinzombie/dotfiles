[CmdletBinding()]
param(
    [switch]$DryRun
)

# Bootstraps a Windows machine: installs git and the GitHub CLI via winget,
# makes sure gh is authenticated, and installs the dotfiles commands into
# ~/.local/bin. Safe to run multiple times.

Set-StrictMode -Version Latest
$ErrorActionPreference = 'Stop'

$rootDir = $PSScriptRoot
$binDir = Join-Path $HOME ".local/bin"

function Test-CommandExists {
    param([Parameter(Mandatory = $true)][string]$CommandName)
    return [bool](Get-Command $CommandName -ErrorAction SilentlyContinue)
}

function Install-WingetPackage {
    param(
        [Parameter(Mandatory = $true)][string]$CommandName,
        [Parameter(Mandatory = $true)][string]$WingetId
    )

    if (Test-CommandExists $CommandName) {
        Write-Host "[ ok ] $CommandName already installed"
        return
    }

    Write-Host "[info] Installing $CommandName..."
    if ($DryRun) {
        Write-Host "[dry-run] winget install --id $WingetId -e"
        return
    }

    winget install --id $WingetId -e --accept-source-agreements --accept-package-agreements
    if ($LASTEXITCODE -ne 0) {
        throw "winget failed to install $WingetId."
    }

    # winget updates the persisted PATH only; reload it so gh/git are usable
    # later in this same script without restarting the terminal.
    $env:Path = [Environment]::GetEnvironmentVariable("Path", "Machine") + ";" +
        [Environment]::GetEnvironmentVariable("Path", "User")
}

if (-not (Test-CommandExists "winget")) {
    throw "winget was not found. Install 'App Installer' from the Microsoft Store and re-run."
}

Install-WingetPackage -CommandName "git" -WingetId "Git.Git"
Install-WingetPackage -CommandName "gh" -WingetId "GitHub.cli"

# Authentication is skipped on dry runs because gh auth login is interactive.
if (-not $DryRun -and (Test-CommandExists "gh")) {
    gh auth status *> $null
    if ($LASTEXITCODE -eq 0) {
        Write-Host "[ ok ] gh is authenticated"
    } else {
        Write-Host "[info] gh is not authenticated, starting login..."
        gh auth login
    }
}

function Install-CommandScript {
    param(
        [Parameter(Mandatory = $true)][string]$Source,
        [Parameter(Mandatory = $true)][string]$Target,
        [Parameter(Mandatory = $true)][string]$CommandName,
        [Parameter(Mandatory = $true)][string]$AliasName
    )

    if (-not (Test-Path -LiteralPath $Target -PathType Leaf)) {
        $status = "missing; would install"
    } elseif ((Get-FileHash -LiteralPath $Source).Hash -eq (Get-FileHash -LiteralPath $Target).Hash) {
        $status = "already up to date"
        if ($DryRun) {
            Write-Host "[ ok ] $CommandName $status"
            return
        }
    } else {
        $status = "out of date; would update"
    }

    if ($DryRun) {
        Write-Host "[info] $CommandName $status"
        Write-Host "[dry-run] copy $Source -> $Target"
    } else {
        New-Item -ItemType Directory -Path $binDir -Force | Out-Null
        Copy-Item -LiteralPath $Source -Destination $Target -Force
        Write-Host "[ ok ] Installed $CommandName (also available as: git $AliasName, requires Git Bash)"
    }
}

# Unlike the git commands, this one is a wrapper that runs the script from this
# checkout, because it needs the tracked vscode/extensions.txt next to it.
# It is a Git Bash script, so the path is written in forward-slash form.
function Install-CommandWrapper {
    param(
        [Parameter(Mandatory = $true)][string]$Script,
        [Parameter(Mandatory = $true)][string]$Target,
        [Parameter(Mandatory = $true)][string]$CommandName
    )

    $scriptPath = $Script -replace '\\', '/'
    $content = "#!/usr/bin/env bash`n# Generated by dotfiles setup; runs the script from the dotfiles checkout.`nexec '$scriptPath' `"`$@`"`n"

    if (-not (Test-Path -LiteralPath $Target -PathType Leaf)) {
        $status = "missing; would install"
    } elseif ([System.IO.File]::ReadAllText($Target) -ceq $content) {
        $status = "already up to date"
        if ($DryRun) {
            Write-Host "[ ok ] $CommandName $status"
            return
        }
    } else {
        $status = "out of date; would update"
    }

    if ($DryRun) {
        Write-Host "[info] $CommandName $status"
        Write-Host "[dry-run] write wrapper $Target -> $scriptPath"
    } else {
        New-Item -ItemType Directory -Path $binDir -Force | Out-Null
        # UTF-8 without BOM and LF endings so bash can read the shebang.
        [System.IO.File]::WriteAllText($Target, $content, (New-Object System.Text.UTF8Encoding($false)))
        Write-Host "[ ok ] Installed $CommandName (runs $scriptPath, requires Git Bash)"
    }
}

Write-Host "[info] Installing commands into $binDir"
# Copied without the .sh extension so Git for Windows exposes them as Git commands.
Install-CommandScript `
    -Source (Join-Path $rootDir "git/git-sync-fork.sh") `
    -Target (Join-Path $binDir "git-sync-fork") `
    -CommandName "git-sync-fork" `
    -AliasName "sync-fork"
Install-CommandScript `
    -Source (Join-Path $rootDir "git/git-prune-branches.sh") `
    -Target (Join-Path $binDir "git-prune-branches") `
    -CommandName "git-prune-branches" `
    -AliasName "prune-branches"
Install-CommandWrapper `
    -Script (Join-Path $rootDir "vscode/sync-extensions.sh") `
    -Target (Join-Path $binDir "vscode-sync-extensions") `
    -CommandName "vscode-sync-extensions"

# Persist the bin directory on the user PATH (takes effect in new terminals).
$userPath = [Environment]::GetEnvironmentVariable("Path", "User")
if (($userPath -split ";") -notcontains $binDir) {
    if ($DryRun) {
        Write-Host "[dry-run] add $binDir to user PATH"
    } else {
        [Environment]::SetEnvironmentVariable("Path", "$userPath;$binDir", "User")
        Write-Host "[ ok ] Added $binDir to your user PATH. Restart your terminal to use it."
    }
}

Write-Host "[ ok ] Setup complete"
